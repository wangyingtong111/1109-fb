def _has_embedded_constraints(sequence):
    """Detect non-None tags in a partially tagged token sequence."""
    try:
        for token in sequence:
            if (
                isinstance(token, (tuple, list))
                and len(token) == 2
                and token[_TAG] is not None
            ):
                return True
    except TypeError:
        return False
    return False


