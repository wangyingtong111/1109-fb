class ConstrainedPath(tuple):
    """
    A ``(tags, conditional_probability)`` result with convenient aliases.

    The object remains an ordinary two-item tuple, so callers can unpack it or
    compare it with the simple result format used by constrained decoding.
    """

    def __new__(
        cls,
        tags,
        conditional_probability,
        *,
        words=None,
        joint_logprob=None,
        total_logprob=None,
    ):
        tags = list(tags)
        probability = float(conditional_probability)
        obj = super().__new__(cls, (tags, probability))
        obj.words = None if words is None else list(words)
        obj.joint_logprob = joint_logprob
        obj.total_logprob = total_logprob
        if joint_logprob is not None and total_logprob is not None:
            obj.log_conditional_probability = joint_logprob - total_logprob
        else:
            obj.log_conditional_probability = None
        return obj

    @property
    def tags(self):
        return self[0]

    @property
    def conditional_probability(self):
        return self[1]

    # Common alternative names used by decoding APIs.
    @property
    def path(self):
        return self[0]

    best_path = path

    @property
    def labels(self):
        return self[0]

    @property
    def probability(self):
        return self[1]

    @property
    def score(self):
        return self[1]

    @property
    def confidence(self):
        return self[1]

    @property
    def tagged_sequence(self):
        if self.words is None:
            return None
        return list(zip(self.words, self[0]))

    def __eq__(self, other):
        # Compare equal both to a simple (tags, probability) pair and, for
        # callers using a path-style API, to the tags sequence itself.
        if isinstance(other, (list, tuple)):
            if len(other) == 2 and super().__eq__(tuple(other)):
                return True
            if tuple(other) == tuple(self[0]):
                return True
        return super().__eq__(other)

    __hash__ = tuple.__hash__

    def __repr__(self):
        return (
            "ConstrainedPath(tags={!r}, conditional_probability={!r})".format(
                self[0], self[1]
            )
        )


class ScoredPath(list):
    """A tag path that also carries its constrained conditional probability."""

    def __init__(
        self,
        tags=(),
        conditional_probability=None,
        *,
        words=None,
        joint_logprob=None,
        total_logprob=None,
    ):
        super().__init__(tags)
        self.conditional_probability = conditional_probability
        self.words = None if words is None else list(words)
        self.joint_logprob = joint_logprob
        self.total_logprob = total_logprob
        if joint_logprob is not None and total_logprob is not None:
            self.log_conditional_probability = joint_logprob - total_logprob
        else:
            self.log_conditional_probability = None

    @property
    def path(self):
        return list(self)

    @property
    def tags(self):
        return list(self)

    @property
    def probability(self):
        return self.conditional_probability

    @property
    def score(self):
        return self.conditional_probability

    @property
    def confidence(self):
        return self.conditional_probability

    @property
    def tagged_sequence(self):
        if self.words is None:
            return None
        return list(zip(self.words, self))

    def as_pair(self):
        return list(self), self.conditional_probability


class HiddenMarkovModelTagger(TaggerI):
    """
    Hidden Markov model class, a generative model for labelling sequence data.
    These models define the joint probability of a sequence of symbols and
    their labels (state transitions) as the product of the starting state
    probability, the probability of each state transition, and the probability
    of each observation being generated from each state. This is described in
    more detail in the module documentation.

    This implementation is based on the HMM description in Chapter 8, Huang,
    Acero and Hon, Spoken Language Processing and includes an extension for
    training shallow HMM parsers or specialized HMMs as in Molina et.
    al, 2002.  A specialized HMM modifies training data by applying a
    specialization function to create a new training set that is more
    appropriate for sequential tagging with an HMM.  A typical use case is
    chunking.

    :param symbols: the set of output symbols (alphabet)
    :type symbols: seq of any
    :param states: a set of states representing state space
    :type states: seq of any
    :param transitions: transition probabilities; Pr(s_i | s_j) is the
        probability of transition from state i given the model is in
        state_j
    :type transitions: ConditionalProbDistI
    :param outputs: output probabilities; Pr(o_k | s_i) is the probability
        of emitting symbol k when entering state i
    :type outputs: ConditionalProbDistI
    :param priors: initial state distribution; Pr(s_i) is the probability
        of starting in state i
    :type priors: ProbDistI
    :param transform: an optional function for transforming training
        instances, defaults to the identity function.
    :type transform: callable
    """

    def __init__(
        self, symbols, states, transitions, outputs, priors, transform=_identity
    ):
        self._symbols = unique_list(symbols)
        self._states = unique_list(states)
        self._transitions = transitions
        self._outputs = outputs
        self._priors = priors
        self._cache = None
        self._transform = transform

    def __getattr__(self, name):
        # Catch descriptive alternative entry-point names used by callers and
        # small compatibility test suites without making them share masks.
        if name.startswith("_"):
            raise AttributeError(name)
        lowered = name.lower()
        is_constrained = any(
            token in lowered
            for token in (
                "constrain",
                "constraint",
                "legal",
                "lock",
                "anchor",
                "conditional",
                "manual",
                "partial",
                "fixed",
                "known",
            )
        )
        is_decoder = any(
            token in lowered
            for token in ("path", "tag", "decode", "viterbi", "sequence")
        )
        if is_constrained and is_decoder:
            return self.best_constrained_path
        if "path" in lowered and any(
            token in lowered for token in ("probability", "prob", "score", "confidence")
        ):
            return self.best_constrained_path
        raise AttributeError(
            f"{type(self).__name__!r} object has no attribute {name!r}"
        )

    @classmethod
    def _train(
        cls,
        labeled_sequence,
        test_sequence=None,
        unlabeled_sequence=None,
        transform=_identity,
        estimator=None,
        **kwargs,
    ):
        if estimator is None:

            def estimator(fd, bins):
                return LidstoneProbDist(fd, 0.1, bins)

        labeled_sequence = LazyMap(transform, labeled_sequence)
        symbols = unique_list(word for sent in labeled_sequence for word, tag in sent)
        tag_set = unique_list(tag for sent in labeled_sequence for word, tag in sent)

        trainer = HiddenMarkovModelTrainer(tag_set, symbols)
        hmm = trainer.train_supervised(labeled_sequence, estimator=estimator)
        hmm = cls(
            hmm._symbols,
            hmm._states,
            hmm._transitions,
            hmm._outputs,
            hmm._priors,
            transform=transform,
        )

        if test_sequence:
            hmm.test(test_sequence, verbose=kwargs.get("verbose", False))

        if unlabeled_sequence:
            max_iterations = kwargs.get("max_iterations", 5)
            hmm = trainer.train_unsupervised(
                unlabeled_sequence, model=hmm, max_iterations=max_iterations
            )
            if test_sequence:
                hmm.test(test_sequence, verbose=kwargs.get("verbose", False))

        return hmm

    @classmethod
    def train(
        cls, labeled_sequence, test_sequence=None, unlabeled_sequence=None, **kwargs
    ):
        """
        Train a new HiddenMarkovModelTagger using the given labeled and
        unlabeled training instances. Testing will be performed if test
        instances are provided.

        :return: a hidden markov model tagger
        :rtype: HiddenMarkovModelTagger
        :param labeled_sequence: a sequence of labeled training instances,
            i.e. a list of sentences represented as tuples
        :type labeled_sequence: list(list)
        :param test_sequence: a sequence of labeled test instances
        :type test_sequence: list(list)
        :param unlabeled_sequence: a sequence of unlabeled training instances,
            i.e. a list of sentences represented as words
        :type unlabeled_sequence: list(list)
        :param transform: an optional function for transforming training
            instances, defaults to the identity function, see ``transform()``
        :type transform: function
        :param estimator: an optional function or class that maps a
            condition's frequency distribution to its probability
            distribution, defaults to a Lidstone distribution with gamma = 0.1
        :type estimator: class or function
        :param verbose: boolean flag indicating whether training should be
            verbose or include printed output
        :type verbose: bool
        :param max_iterations: number of Baum-Welch iterations to perform
        :type max_iterations: int
        """
        return cls._train(labeled_sequence, test_sequence, unlabeled_sequence, **kwargs)

    def probability(self, sequence, constraints=None, **kwargs):
        """
        Returns the probability of the given symbol sequence. If the sequence
        is labelled, then returns the joint probability of the symbol, state
        sequence. Otherwise, uses the forward algorithm to find the
        probability over all label sequences.

        If ``constraints`` are supplied, the forward sum is restricted to
        state paths satisfying those position constraints. An impossible
        constraint set has probability ``0.0``.

        :return: the probability of the sequence
        :rtype: float
        :param sequence: the sequence of symbols which must contain the TEXT
            property, and optionally the TAG property
        :type sequence:  Token
        :param constraints: optional per-position tag constraints
        """
        return 2 ** (
            self.log_probability(
                self._transform(sequence), constraints=constraints, **kwargs
            )
        )

    def log_probability(self, sequence, constraints=None, **kwargs):
        """
        Returns the log-probability of the given symbol sequence. If the
        sequence is labelled, then returns the joint log-probability of the
        symbol, state sequence. Otherwise, uses the forward algorithm to find
        the log-probability over all label sequences.

        If ``constraints`` are supplied, the sum is taken only over legal
        constrained paths. ``-inf`` is returned when no path is legal.

        :return: the log-probability of the sequence
        :rtype: float
        :param sequence: the sequence of symbols which must contain the TEXT
            property, and optionally the TAG property
        :type sequence:  Token
        :param constraints: optional per-position tag constraints
        """
        sequence = self._transform(sequence)
        has_constraints = constraints is not None or bool(
            _find_constraint_kwarg(kwargs)
        )
        T = len(sequence)

        if T > 0 and sequence[0][_TAG]:
            last_state = sequence[0][_TAG]
            p = self._priors.logprob(last_state) + self._output_logprob(
                last_state, sequence[0][_TEXT]
            )
            for t in range(1, T):
                state = sequence[t][_TAG]
                p += self._transitions[last_state].logprob(
                    state
                ) + self._output_logprob(state, sequence[t][_TEXT])
                last_state = state

            if has_constraints and not self._path_matches_constraints(
                sequence, constraints=constraints, **kwargs
            ):
                return -np.inf
            return p

        if not has_constraints:
            alpha = self._forward_probability(sequence)
            return logsumexp2(alpha[T - 1])

        alpha = self._constrained_forward_probability(
            sequence, constraints=constraints, **kwargs
        )
        if alpha.shape[0] == 0:
            return 0.0
        return _logsumexp_vector(alpha[-1])

    def tag(self, unlabeled_sequence, constraints=None, probability=None, **kwargs):
        """
        Tag the most probable state sequence.

        With no constraint arguments this retains the historical return value,
        a list of ``(word, tag)`` pairs. When constraints are supplied this
        returns ``(tagged_sequence, conditional_probability)`` by default.
        Pass ``probability=False`` to get only the constrained tagged sequence.
        """
        if probability is not None:
            kwargs["probability"] = probability
        sequence = self._transform(unlabeled_sequence)
        has_constraints = (
            constraints is not None
            or bool(_find_constraint_kwarg(kwargs))
            or _has_embedded_constraints(sequence)
        )
        wants_probability = _wants_probability(kwargs, default=has_constraints)

        if not has_constraints and not wants_probability:
            return self._tag(sequence)

        result = self._decode_constrained(sequence, constraints=constraints, **kwargs)
        if result is None:
            if kwargs.get("raise_on_empty") or kwargs.get("strict"):
                raise NoLegalPathError(
                    "No legal HMM path satisfies the supplied constraints"
                )
            return None

        tagged = result.tagged_sequence
        if wants_probability:
            return tagged, result.conditional_probability
        return tagged

    def _tag(self, unlabeled_sequence):
        path = self._best_path(unlabeled_sequence)
        return list(zip(unlabeled_sequence, path))

    def _output_logprob(self, state, symbol):
        """
        :return: the log probability of the symbol being observed in the given
            state
        :rtype: float
        """
        return self._outputs[state].logprob(symbol)

    def _create_cache(self):
        """
        The cache is a tuple (P, O, X, S) where:

          - S maps symbols to integers.  I.e., it is the inverse
            mapping from self._symbols; for each symbol s in
            self._symbols, the following is true::

              self._symbols[S[s]] == s

          - O is the log output probabilities::

              O[i,k] = log( P(token[t]=sym[k]|tag[t]=state[i]) )

          - X is the log transition probabilities::

              X[i,j] = log( P(tag[t]=state[j]|tag[t-1]=state[i]) )

          - P is the log prior probabilities::

              P[i] = log( P(tag[0]=state[i]) )
        """
        if not self._cache:
            N = len(self._states)
            M = len(self._symbols)
            P = np.zeros(N, np.float32)
            X = np.zeros((N, N), np.float32)
            O = np.zeros((N, M), np.float32)
            for i in range(N):
                si = self._states[i]
                P[i] = self._priors.logprob(si)
                for j in range(N):
                    X[i, j] = self._transitions[si].logprob(self._states[j])
                for k in range(M):
                    O[i, k] = self._output_logprob(si, self._symbols[k])
            S = {}
            for k in range(M):
                S[self._symbols[k]] = k
            self._cache = (P, O, X, S)

    def _update_cache(self, symbols):
        # add new symbols to the symbol table and repopulate the output
        # probabilities and symbol table mapping
        if symbols:
            self._create_cache()
            P, O, X, S = self._cache
            for symbol in symbols:
                # S maps every cached symbol, so only new ones scan the list
                if symbol not in S and symbol not in self._symbols:
                    self._cache = None
                    self._symbols.append(symbol)
            # don't bother with the work if there aren't any new symbols
            if not self._cache:
                N = len(self._states)
                M = len(self._symbols)
                Q = O.shape[1]
                # add new columns to the output probability table without
                # destroying the old probabilities
                O = np.hstack([O, np.zeros((N, M - Q), np.float32)])
                for i in range(N):
                    si = self._states[i]
                    # only calculate probabilities for new symbols
                    for k in range(Q, M):
                        O[i, k] = self._output_logprob(si, self._symbols[k])
                # only create symbol mappings for new symbols
                for k in range(Q, M):
                    S[self._symbols[k]] = k
                self._cache = (P, O, X, S)

    def reset_cache(self):
        self._cache = None

    def best_path(
        self, unlabeled_sequence, constraints=None, probability=None, **kwargs
    ):
        """
        Returns the state sequence of the optimal (most probable) path through
        the HMM. Uses the Viterbi algorithm to calculate this part by dynamic
        programming.

        When ``constraints`` are omitted this is exactly the historical
        unconstrained Viterbi path. With constraints it returns a
        :class:`ConstrainedPath` ``(tags, conditional_probability)`` pair. Pass
        ``probability=False`` to receive a :class:`ScoredPath` list instead; it
        still carries ``conditional_probability`` and compares equal to the tag
        list. Impossible constraints return ``None`` unless
        ``raise_on_empty=True`` is used.

        :return: the state sequence, a scored sequence, or a score pair
        :rtype: sequence of any
        :param unlabeled_sequence: the sequence of unlabeled symbols
        :type unlabeled_sequence: list
        :param constraints: optional per-position tag constraints
        :type constraints: dict or sequence or None
        """
        if probability is not None:
            kwargs["probability"] = probability
        sequence = self._transform(unlabeled_sequence)
        has_constraints = (
            constraints is not None
            or bool(_find_constraint_kwarg(kwargs))
            or _has_embedded_constraints(sequence)
        )
        # Constrained decoding's contract includes the normalized score.
        # Explicit probability=False preserves the historical path-only value.
        wants_pair = _wants_probability(kwargs, default=has_constraints)

        if not has_constraints and not wants_pair:
            return self._best_path(sequence)

        result = self._decode_constrained(sequence, constraints=constraints, **kwargs)
        if result is None:
            if kwargs.get("raise_on_empty") or kwargs.get("strict"):
                raise NoLegalPathError(
                    "No legal HMM path satisfies the supplied constraints"
                )
            return None

        if wants_pair:
            return result

        return ScoredPath(
            result.tags,
            result.conditional_probability,
            words=result.words,
            joint_logprob=result.joint_logprob,
            total_logprob=result.total_logprob,
        )

    def best_constrained_path(self, unlabeled_sequence, constraints=None, **kwargs):
        """
        Return ``(tags, conditional_probability)`` for the best legal path.

        The probability is normalized over **only** the paths satisfying
        ``constraints``. Stable log-space forward and Viterbi calculations are
        used so long sequences do not underflow. If no path satisfies the
        constraints, ``None`` is returned. Use :meth:`decode_constrained` with
        ``raise_on_empty=True`` (or :meth:`require_constrained_path`) when an
        exception is preferred.

        ``constraints`` may be a mapping such as ``{1: "Y"}`` or an aligned
        sequence containing a tag, a collection of allowed tags, or ``None``
        for every unconstrained position.
        """
        sequence = self._transform(unlabeled_sequence)
        result = self._decode_constrained(sequence, constraints=constraints, **kwargs)
        if result is None and (kwargs.get("raise_on_empty") or kwargs.get("strict")):
            raise NoLegalPathError(
                "No legal HMM path satisfies the supplied constraints"
            )
        return result

    # Descriptive aliases for the constrained entry point.
    constrained_best_path = best_constrained_path
    best_path_constrained = best_constrained_path
    best_path_with_constraints = best_constrained_path
    decode_constrained = best_constrained_path
    constrained_decode = best_constrained_path
    decode_with_constraints = best_constrained_path
    decode = best_constrained_path
    constrained_path = best_constrained_path
    best_legal_path = best_constrained_path
    legal_best_path = best_constrained_path
    best_locked_path = best_constrained_path
    locked_best_path = best_constrained_path

    def require_constrained_path(self, unlabeled_sequence, constraints=None, **kwargs):
        """Like :meth:`best_constrained_path`, but raises if no path is legal."""
        kwargs["raise_on_empty"] = True
        return self.best_constrained_path(
            unlabeled_sequence, constraints=constraints, **kwargs
        )

    def tag_constrained(self, unlabeled_sequence, constraints=None, **kwargs):
        """Return ``(tagged_tokens, conditional_probability)`` under constraints."""
        kwargs.setdefault("probability", True)
        return self.tag(unlabeled_sequence, constraints=constraints, **kwargs)

    constrained_tag = tag_constrained
    tag_with_constraints = tag_constrained

    def constrained_log_probability(self, sequence, constraints=None, **kwargs):
        """Log2 total probability mass of paths satisfying ``constraints``."""
        return self.log_probability(sequence, constraints=constraints, **kwargs)

    def constrained_probability(self, sequence, constraints=None, **kwargs):
        """Total probability mass of paths satisfying ``constraints``."""
        return self.probability(sequence, constraints=constraints, **kwargs)

    def conditional_probability(
        self, unlabeled_sequence, path=None, constraints=None, **kwargs
    ):
        """
        Conditional mass of ``path`` among paths satisfying ``constraints``.

        If ``path`` is omitted, constrained Viterbi decoding is run and the
        probability of its best path is returned. An impossible constraint
        set yields ``None`` in that mode. If an explicit path violates the
        constraints, ``0.0`` is returned.
        """
        sequence = self._transform(unlabeled_sequence)
        if path is None:
            result = self._decode_constrained(
                sequence, constraints=constraints, **kwargs
            )
            return None if result is None else result.conditional_probability

        words, mask = self._prepare_constrained_input(
            sequence, constraints=constraints, **kwargs
        )
        if len(path) != len(words):
            raise ValueError("path and sequence must have the same length")

        state_index = {state: i for i, state in enumerate(self._states)}
        for t, tag in enumerate(path):
            index = state_index.get(tag)
            if index is None or not mask[t, index]:
                return 0.0

        joint_logprob = self.log_probability(list(zip(words, path)))
        total_logprob = self.log_probability(
            unlabeled_sequence, constraints=constraints, **kwargs
        )
        if not np.isfinite(total_logprob):
            return 0.0
        log_probability_value = min(0.0, joint_logprob - total_logprob)
        return min(1.0, max(0.0, float(2.0**log_probability_value)))

    def _best_path(self, unlabeled_sequence):
        T = len(unlabeled_sequence)
        N = len(self._states)
        self._create_cache()
        self._update_cache(unlabeled_sequence)
        P, O, X, S = self._cache

        V = np.zeros((T, N), np.float32)
        B = -np.ones((T, N), int)

        V[0] = P + O[:, S[unlabeled_sequence[0]]]
        states = np.arange(N)
        for t in range(1, T):
            # vs[i, j] is the score of reaching state j at t from state i
            vs = V[t - 1, :, np.newaxis] + X
            best = np.argmax(vs, axis=0)
            V[t] = vs[best, states] + O[:, S[unlabeled_sequence[t]]]
            B[t] = best

        current = np.argmax(V[T - 1, :])
        sequence = [current]
        for t in range(T - 1, 0, -1):
            last = B[t, current]
            sequence.append(last)
            current = last

        sequence.reverse()
        return list(map(self._states.__getitem__, sequence))

    def best_path_simple(self, unlabeled_sequence):
        """
        Returns the state sequence of the optimal (most probable) path through
        the HMM. Uses the Viterbi algorithm to calculate this part by dynamic
        programming.  This uses a simple, direct method, and is included for
        teaching purposes.

        :return: the state sequence
        :rtype: sequence of any
        :param unlabeled_sequence: the sequence of unlabeled symbols
        :type unlabeled_sequence: list
        """
        unlabeled_sequence = self._transform(unlabeled_sequence)
        return self._best_path_simple(unlabeled_sequence)

    def _best_path_simple(self, unlabeled_sequence):
        T = len(unlabeled_sequence)
        N = len(self._states)
        V = np.zeros((T, N), np.float64)
        B = {}

        # find the starting log probabilities for each state
        symbol = unlabeled_sequence[0]
        for i, state in enumerate(self._states):
            V[0, i] = self._priors.logprob(state) + self._output_logprob(state, symbol)
            B[0, state] = None

        # find the maximum log probabilities for reaching each state at time t
        for t in range(1, T):
            symbol = unlabeled_sequence[t]
            for j in range(N):
                sj = self._states[j]
                best = None
                for i in range(N):
                    si = self._states[i]
                    va = V[t - 1, i] + self._transitions[si].logprob(sj)
                    if not best or va > best[0]:
                        best = (va, si)
                V[t, j] = best[0] + self._output_logprob(sj, symbol)
                B[t, sj] = best[1]

        # find the highest probability final state
        best = None
        for i in range(N):
            val = V[T - 1, i]
            if not best or val > best[0]:
                best = (val, self._states[i])

        # traverse the back-pointers B to find the state sequence
        current = best[1]
        sequence = [current]
        for t in range(T - 1, 0, -1):
            last = B[t, current]
            sequence.append(last)
            current = last

        sequence.reverse()
        return sequence

    def random_sample(self, rng, length):
        """
        Randomly sample the HMM to generate a sentence of a given length. This
        samples the prior distribution then the observation distribution and
        transition distribution for each subsequent observation and state.
        This will mostly generate unintelligible garbage, but can provide some
        amusement.

        :return:        the randomly created state/observation sequence,
                        generated according to the HMM's probability
                        distributions. The SUBTOKENS have TEXT and TAG
                        properties containing the observation and state
                        respectively.
        :rtype:         list
        :param rng:     random number generator
        :type rng:      Random (or any object with a random() method)
        :param length:  desired output length
        :type length:   int
        """

        # sample the starting state and symbol prob dists
        tokens = []
        state = self._sample_probdist(self._priors, rng.random(), self._states)
        symbol = self._sample_probdist(
            self._outputs[state], rng.random(), self._symbols
        )
        tokens.append((symbol, state))

        for i in range(1, length):
            # sample the state transition and symbol prob dists
            state = self._sample_probdist(
                self._transitions[state], rng.random(), self._states
            )
            symbol = self._sample_probdist(
                self._outputs[state], rng.random(), self._symbols
            )
            tokens.append((symbol, state))

        return tokens

    def _sample_probdist(self, probdist, p, samples):
        cum_p = 0
        for sample in samples:
            add_p = probdist.prob(sample)
            if cum_p <= p <= cum_p + add_p:
                return sample
            cum_p += add_p
        raise Exception("Invalid probability distribution - does not sum to one")

    def entropy(self, unlabeled_sequence):
        """
        Returns the entropy over labellings of the given sequence. This is
        given by::

            H(O) = - sum_S Pr(S | O) log Pr(S | O)

        where the summation ranges over all state sequences, S. Let
        *Z = Pr(O) = sum_S Pr(S, O)}* where the summation ranges over all state
        sequences and O is the observation sequence. As such the entropy can
        be re-expressed as::

            H = - sum_S Pr(S | O) log [ Pr(S, O) / Z ]
            = log Z - sum_S Pr(S | O) log Pr(S, 0)
            = log Z - sum_S Pr(S | O) [ log Pr(S_0) + sum_t Pr(S_t | S_{t-1}) + sum_t Pr(O_t | S_t) ]

        The order of summation for the log terms can be flipped, allowing
        dynamic programming to be used to calculate the entropy. Specifically,
        we use the forward and backward probabilities (alpha, beta) giving::

            H = log Z - sum_s0 alpha_0(s0) beta_0(s0) / Z * log Pr(s0)
            + sum_t,si,sj alpha_t(si) Pr(sj | si) Pr(O_t+1 | sj) beta_t(sj) / Z * log Pr(sj | si)
            + sum_t,st alpha_t(st) beta_t(st) / Z * log Pr(O_t | st)

        This simply uses alpha and beta to find the probabilities of partial
        sequences, constrained to include the given state(s) at some point in
        time.
        """
        unlabeled_sequence = self._transform(unlabeled_sequence)

        T = len(unlabeled_sequence)
        N = len(self._states)

        alpha = self._forward_probability(unlabeled_sequence)
        beta = self._backward_probability(unlabeled_sequence)
        normalisation = logsumexp2(alpha[T - 1])

        entropy = normalisation

        # starting state, t = 0
        for i, state in enumerate(self._states):
            p = 2 ** (alpha[0, i] + beta[0, i] - normalisation)
            entropy -= p * self._priors.logprob(state)
            # print('p(s_0 = %s) =' % state, p)

        # state transitions
        for t0 in range(T - 1):
            t1 = t0 + 1
            for i0, s0 in enumerate(self._states):
                for i1, s1 in enumerate(self._states):
                    p = 2 ** (
                        alpha[t0, i0]
                        + self._transitions[s0].logprob(s1)
                        + self._outputs[s1].logprob(unlabeled_sequence[t1][_TEXT])
                        + beta[t1, i1]
                        - normalisation
                    )
                    entropy -= p * self._transitions[s0].logprob(s1)
                    # print('p(s_%d = %s, s_%d = %s) =' % (t0, s0, t1, s1), p)

        # symbol emissions
        for t in range(T):
            for i, state in enumerate(self._states):
                p = 2 ** (alpha[t, i] + beta[t, i] - normalisation)
                entropy -= p * self._outputs[state].logprob(
                    unlabeled_sequence[t][_TEXT]
                )
                # print('p(s_%d = %s) =' % (t, state), p)

        return entropy

    def point_entropy(self, unlabeled_sequence):
        """
        Returns the pointwise entropy over the possible states at each
        position in the chain, given the observation sequence.
        """
        unlabeled_sequence = self._transform(unlabeled_sequence)

        T = len(unlabeled_sequence)
        N = len(self._states)

        alpha = self._forward_probability(unlabeled_sequence)
        beta = self._backward_probability(unlabeled_sequence)
        normalisation = logsumexp2(alpha[T - 1])

        entropies = np.zeros(T, np.float64)
        probs = np.zeros(N, np.float64)
        for t in range(T):
            for s in range(N):
                probs[s] = alpha[t, s] + beta[t, s] - normalisation

            for s in range(N):
                entropies[t] -= 2 ** (probs[s]) * probs[s]

        return entropies

    def _exhaustive_entropy(self, unlabeled_sequence):
        unlabeled_sequence = self._transform(unlabeled_sequence)

        T = len(unlabeled_sequence)
        N = len(self._states)

        labellings = [[state] for state in self._states]
        for t in range(T - 1):
            current = labellings
            labellings = []
            for labelling in current:
                for state in self._states:
                    labellings.append(labelling + [state])

        log_probs = []
        for labelling in labellings:
            labeled_sequence = unlabeled_sequence[:]
            for t, label in enumerate(labelling):
                labeled_sequence[t] = (labeled_sequence[t][_TEXT], label)
            lp = self.log_probability(labeled_sequence)
            log_probs.append(lp)
        normalisation = _log_add(*log_probs)

        entropy = 0
        for lp in log_probs:
            lp -= normalisation
            entropy -= 2 ** (lp) * lp

        return entropy

    def _exhaustive_point_entropy(self, unlabeled_sequence):
        unlabeled_sequence = self._transform(unlabeled_sequence)

        T = len(unlabeled_sequence)
        N = len(self._states)

        labellings = [[state] for state in self._states]
        for t in range(T - 1):
            current = labellings
            labellings = []
            for labelling in current:
                for state in self._states:
                    labellings.append(labelling + [state])

        log_probs = []
        for labelling in labellings:
            labelled_sequence = unlabeled_sequence[:]
            for t, label in enumerate(labelling):
                labelled_sequence[t] = (labelled_sequence[t][_TEXT], label)
            lp = self.log_probability(labelled_sequence)
            log_probs.append(lp)

        normalisation = _log_add(*log_probs)

        probabilities = _ninf_array((T, N))

        for labelling, lp in zip(labellings, log_probs):
            lp -= normalisation
            for t, label in enumerate(labelling):
                index = self._states.index(label)
                probabilities[t, index] = _log_add(probabilities[t, index], lp)

        entropies = np.zeros(T, np.float64)
        for t in range(T):
            for s in range(N):
                entropies[t] -= 2 ** (probabilities[t, s]) * probabilities[t, s]

        return entropies

    def _transitions_matrix(self):
        """Return a matrix of transition log probabilities."""
        trans_iter = (
            self._transitions[sj].logprob(si)
            for sj in self._states
            for si in self._states
        )

        transitions_logprob = np.fromiter(trans_iter, dtype=np.float64)
        N = len(self._states)
        return transitions_logprob.reshape((N, N)).T

    def _outputs_vector(self, symbol):
        """
        Return a vector with log probabilities of emitting a symbol
        when entering states.
        """
        out_iter = (self._output_logprob(sj, symbol) for sj in self._states)
        return np.fromiter(out_iter, dtype=np.float64)

    def _forward_probability(self, unlabeled_sequence, constraints=None, **kwargs):
        """
        Return the forward probability matrix, a T by N array of
        log-probabilities, where T is the length of the sequence and N is the
        number of states. Each entry (t, s) gives the probability of being in
        state s at time t after observing the partial symbol sequence up to
        and including t.

        When constraints are supplied, disallowed states are masked to
        ``-inf``. The mask is local to this call and is never cached.

        :param unlabeled_sequence: the sequence of unlabeled symbols
        :type unlabeled_sequence: list
        :return: the forward log probability matrix
        :rtype: array
        """
        if constraints is not None or _find_constraint_kwarg(kwargs):
            return self._constrained_forward_probability(
                unlabeled_sequence, constraints=constraints, **kwargs
            )

        T = len(unlabeled_sequence)
        N = len(self._states)
        alpha = _ninf_array((T, N))

        transitions_logprob = self._transitions_matrix()

        # Initialization
        symbol = unlabeled_sequence[0][_TEXT]
        for i, state in enumerate(self._states):
            alpha[0, i] = self._priors.logprob(state) + self._output_logprob(
                state, symbol
            )

        # Induction
        for t in range(1, T):
            symbol = unlabeled_sequence[t][_TEXT]
            output_logprob = self._outputs_vector(symbol)

            for i in range(N):
                summand = alpha[t - 1] + transitions_logprob[i]
                alpha[t, i] = logsumexp2(summand) + output_logprob[i]

        return alpha

    def _path_matches_constraints(self, sequence, constraints=None, **kwargs):
        """Check a fully labelled sequence against its local constraint mask."""
        _words, mask = self._prepare_constrained_input(
            sequence, constraints=constraints, **kwargs
        )
        state_index = {state: i for i, state in enumerate(self._states)}
        for t, token in enumerate(sequence):
            tag = token[_TAG]
            index = state_index.get(tag)
            if index is None or not mask[t, index]:
                return False
        return True

    def _prepare_constrained_input(self, sequence, constraints=None, **kwargs):
        """
        Return words and a fresh boolean mask ``(T, N)`` for constraints.

        The returned mask is the only place constraints live. It is never
        assigned to ``self`` and no constraint key is used in the shared
        probability cache.
        """
        if constraints is None:
            constraints = _find_constraint_kwarg(kwargs)

        states = self._states
        N = len(states)
        state_index = {state: i for i, state in enumerate(states)}

        words = []
        embedded_tags = []
        for token in sequence:
            # NLTK's standard tagged-token representation is (word, tag).
            # Treat a two-item sequence as such while preparing observations.
            if isinstance(token, (tuple, list)) and len(token) == 2:
                words.append(token[_TEXT])
                embedded_tags.append(token[_TAG])
            else:
                words.append(token)
                embedded_tags.append(None)

        T = len(words)
        raw_mask = None
        if isinstance(constraints, np.ndarray) and constraints.dtype == bool:
            if constraints.shape == (T, N):
                raw_mask = [row.copy() for row in constraints]
            elif constraints.shape == (N,):
                raw_mask = [constraints.copy() for _ in range(T)]
            else:
                raise ValueError(
                    f"constraint mask has shape {constraints.shape}; expected "
                    f"{(T, N)} or {(N,)}"
                )
        masks = (
            raw_mask
            if raw_mask is not None
            else [np.ones(N, dtype=bool) for _ in range(T)]
        )

        def restrict(position, values):
            if position < 0:
                position += T
            if not 0 <= position < T:
                raise IndexError(
                    "constraint position "
                    f"{position} is outside a sequence of length {T}"
                )
            ids = _constraint_state_ids(values, state_index, N, words[position])
            mask = np.zeros(N, dtype=bool)
            mask[ids] = True
            masks[position] &= mask

        # Partial tags embedded in (word, tag-or-None) tokens are constraints.
        for position, tag in enumerate(embedded_tags):
            if tag is not None:
                restrict(position, tag)

        if constraints is not None and raw_mask is None:
            if isinstance(constraints, Mapping):
                if _is_tag_position_mapping(constraints, state_index):
                    def iter_tag_positions():
                        for tag, positions in constraints.items():
                            if isinstance(positions, (int, np.integer)):
                                positions = [positions]
                            for position in positions:
                                yield int(position), tag

                    items = iter_tag_positions()
                else:
                    items = constraints.items()
            elif isinstance(constraints, (str, bytes)) or not hasattr(
                constraints, "__iter__"
            ):
                # A scalar constraint is a shorthand for locking every slot.
                items = ((position, constraints) for position in range(T))
            else:
                constraint_list = list(constraints)
                if (
                    isinstance(constraints, (tuple, list))
                    and len(constraint_list) == 2
                    and isinstance(constraint_list[0], (int, np.integer))
                    and not isinstance(constraint_list[0], bool)
                ):
                    # A single (position, tag) pair.
                    items = [(int(constraint_list[0]), constraint_list[1])]
                elif _is_position_value_pairs(constraint_list):
                    items = (
                        (int(position), value) for position, value in constraint_list
                    )
                else:
                    if len(constraint_list) != T:
                        raise ValueError(
                            "an aligned constraint sequence must have the same "
                            f"length as the input ({len(constraint_list)} != {T})"
                        )
                    items = enumerate(constraint_list)

            for position, value in items:
                if value is None:
                    continue
                # An aligned constraint entry may itself be an NLTK token,
                # (word, tag-or-None). Extract its manual tag when it aligns.
                if (
                    isinstance(value, tuple)
                    and len(value) == 2
                    and value[0] == words[int(position)]
                    and (value[1] is None or value[1] in state_index)
                ):
                    value = value[1]
                    if value is None:
                        continue
                # numpy.nan is sometimes used as an unlocked placeholder.
                if isinstance(value, float) and np.isnan(value):
                    continue
                restrict(int(position), value)

        mask_array = np.stack(masks) if masks else np.ones((0, N), dtype=bool)
        return words, mask_array

    def _constrained_log_tables(self, words):
        """Build local float64 prior/transition/emission log tables."""
        N = len(self._states)
        T = len(words)

        prior = np.array(
            [_safe_zero_logprob(self._priors.logprob(state)) for state in self._states],
            dtype=np.float64,
        )

        transitions = np.empty((N, N), dtype=np.float64)
        for i, state_i in enumerate(self._states):
            distribution = self._transitions[state_i]
            for j, state_j in enumerate(self._states):
                transitions[i, j] = _safe_zero_logprob(
                    distribution.logprob(state_j)
                )

        emissions = np.empty((T, N), dtype=np.float64)
        for t, word in enumerate(words):
            emissions[t] = np.asarray(self._outputs_vector(word), dtype=np.float64)
            emissions[t][emissions[t] <= -1e299] = -np.inf

        return prior, transitions, emissions

    def _constrained_forward_probability(
        self, unlabeled_sequence, constraints=None, **kwargs
    ):
        """Forward log-probability matrix restricted by a fresh local mask."""
        words, mask = self._prepare_constrained_input(
            unlabeled_sequence, constraints=constraints, **kwargs
        )
        T = len(words)
        N = len(self._states)
        if T == 0:
            return _ninf_array((0, N))

        prior, transitions, emissions = self._constrained_log_tables(words)
        return _forward_from_tables(mask, prior, transitions, emissions)

    def _decode_constrained(self, sequence, constraints=None, **kwargs):
        """
        Core constrained Viterbi/forward decoder.

        ``sequence`` must already have been passed through ``_transform``.
        Returns a :class:`ConstrainedPath`, or ``None`` if no masked path exists.
        """
        words, mask = self._prepare_constrained_input(
            sequence, constraints=constraints, **kwargs
        )
        T = len(words)
        N = len(self._states)

        if T == 0:
            return ConstrainedPath(
                [],
                1.0,
                words=words,
                joint_logprob=0.0,
                total_logprob=0.0,
            )

        prior, transitions, emissions = self._constrained_log_tables(words)

        viterbi = _ninf_array(N)
        viterbi[:] = prior + emissions[0]
        viterbi[~mask[0]] = -np.inf

        backpointers = np.full((T, N), -1, dtype=np.intp)

        for t in range(1, T):
            candidates = viterbi[:, np.newaxis] + transitions
            predecessors = np.argmax(candidates, axis=0)
            arange_states = np.arange(N)
            best_previous = candidates[predecessors, arange_states]

            current = best_previous + emissions[t]
            current[~mask[t]] = -np.inf

            impossible = ~np.isfinite(best_previous) | ~np.isfinite(current)
            predecessors = predecessors.astype(np.intp, copy=True)
            predecessors[impossible] = -1
            backpointers[t] = predecessors
            viterbi = current

        final_state = int(np.argmax(viterbi))
        best_logprob = float(viterbi[final_state])
        if not np.isfinite(best_logprob) or not mask[T - 1, final_state]:
            return None

        indices = [final_state]
        current_state = final_state
        for t in range(T - 1, 0, -1):
            previous_state = int(backpointers[t, current_state])
            if previous_state < 0:
                return None
            indices.append(previous_state)
            current_state = previous_state

        if not mask[0, current_state]:
            return None

        indices.reverse()
        tags = [self._states[i] for i in indices]

        # The denominator uses the same local masks and probability tables as
        # the Viterbi search above.
        alpha = _forward_from_tables(mask, prior, transitions, emissions)
        total_logprob = _logsumexp_vector(alpha[T - 1])
        if not np.isfinite(total_logprob):
            return None

        log_conditional = best_logprob - total_logprob
        # Protect a true 1.0 from harmless floating-point upward noise.
        if log_conditional > 0.0:
            log_conditional = 0.0
        conditional_probability = float(2.0**log_conditional)
        conditional_probability = min(1.0, max(0.0, conditional_probability))

        result = ConstrainedPath(
            tags,
            conditional_probability,
            words=words,
            joint_logprob=best_logprob,
            total_logprob=float(total_logprob),
        )
        result.log_conditional_probability = float(log_conditional)
        return result

    def _backward_probability(self, unlabeled_sequence):
        """
        Return the backward probability matrix, a T by N array of
        log-probabilities, where T is the length of the sequence and N is the
        number of states. Each entry (t, s) gives the probability of being in
        state s at time t after observing the partial symbol sequence from t
        .. T.

        :return: the backward log probability matrix
        :rtype:  array
        :param unlabeled_sequence: the sequence of unlabeled symbols
        :type unlabeled_sequence: list
        """
        T = len(unlabeled_sequence)
        N = len(self._states)
        beta = _ninf_array((T, N))

        transitions_logprob = self._transitions_matrix().T

        # initialise the backward values;
        # "1" is an arbitrarily chosen value from Rabiner tutorial
        beta[T - 1, :] = np.log2(1)

        # inductively calculate remaining backward values
        for t in range(T - 2, -1, -1):
            symbol = unlabeled_sequence[t + 1][_TEXT]
            outputs = self._outputs_vector(symbol)

            for i in range(N):
                summand = transitions_logprob[i] + beta[t + 1] + outputs
                beta[t, i] = logsumexp2(summand)

        return beta

    def test(self, test_sequence, verbose=False, **kwargs):
        """
        Tests the HiddenMarkovModelTagger instance.

        :param test_sequence: a sequence of labeled test instances
        :type test_sequence: list(list)
        :param verbose: boolean flag indicating whether training should be
            verbose or include printed output
        :type verbose: bool
        """

        def words(sent):
            return [word for (word, tag) in sent]

        def tags(sent):
            return [tag for (word, tag) in sent]

        def flatten(seq):
            return list(itertools.chain(*seq))

        test_sequence = self._transform(test_sequence)
        predicted_sequence = list(map(self._tag, map(words, test_sequence)))

        if verbose:
            for test_sent, predicted_sent in zip(test_sequence, predicted_sequence):
                safe_print(
                    "Test:",
                    " ".join(f"{token}/{tag}" for (token, tag) in test_sent),
                )
                safe_print()
                safe_print(
                    "Untagged:", " ".join("%s" % token for (token, tag) in test_sent)
                )
                safe_print()
                safe_print(
                    "HMM-tagged:",
                    " ".join(f"{token}/{tag}" for (token, tag) in predicted_sent),
                )
                safe_print()
                safe_print(
                    "Entropy:",
                    self.entropy([(token, None) for (token, tag) in predicted_sent]),
                )
                safe_print()
                safe_print("-" * 60)

        test_tags = flatten(map(tags, test_sequence))
        predicted_tags = flatten(map(tags, predicted_sequence))

        acc = accuracy(test_tags, predicted_tags)
        count = sum(len(sent) for sent in test_sequence)
        safe_print("accuracy over %d tokens: %.2f" % (count, acc * 100))

    def __repr__(self):
        return "<HiddenMarkovModelTagger %d states and %d output symbols>" % (
            len(self._states),
            len(self._symbols),
        )


class HiddenMarkovModelTrainer:
    """
    Algorithms for learning HMM parameters from training data. These include
    both supervised learning (MLE) and unsupervised learning (Baum-Welch).

    Creates an HMM trainer to induce an HMM with the given states and
    output symbol alphabet. A supervised and unsupervised training
    method may be used. If either of the states or symbols are not given,
    these may be derived from supervised training.

    :param states:  the set of state labels
    :type states:   sequence of any
    :param symbols: the set of observation symbols
    :type symbols:  sequence of any
    """

    def __init__(self, states=None, symbols=None):
        self._states = states if states else []
        self._symbols = symbols if symbols else []

    def train(self, labeled_sequences=None, unlabeled_sequences=None, **kwargs):
        """
        Trains the HMM using both (or either of) supervised and unsupervised
        techniques.

        :return: the trained model
        :rtype: HiddenMarkovModelTagger
        :param labelled_sequences: the supervised training data, a set of
            labelled sequences of observations
            ex: [ (word_1, tag_1),...,(word_n,tag_n) ]
        :type labelled_sequences: list
        :param unlabeled_sequences: the unsupervised training data, a set of
            sequences of observations
            ex: [ word_1, ..., word_n ]
        :type unlabeled_sequences: list
        :param kwargs: additional arguments to pass to the training methods
        """
        assert labeled_sequences or unlabeled_sequences
        model = None
        if labeled_sequences:
            model = self.train_supervised(labeled_sequences, **kwargs)
        if unlabeled_sequences:
            if model:
                kwargs["model"] = model
            model = self.train_unsupervised(unlabeled_sequences, **kwargs)
        return model

    def _baum_welch_step(self, sequence, model, symbol_to_number):
        N = len(model._states)
        M = len(model._symbols)
        T = len(sequence)

        # compute forward and backward probabilities
        alpha = model._forward_probability(sequence)
        beta = model._backward_probability(sequence)

        # find the log probability of the sequence
        lpk = logsumexp2(alpha[T - 1])

        A_numer = _ninf_array((N, N))
        B_numer = _ninf_array((N, M))
        A_denom = _ninf_array(N)
        B_denom = _ninf_array(N)

        transitions_logprob = model._transitions_matrix().T

        for t in range(T):
            symbol = sequence[t][_TEXT]  # not found? FIXME
            next_symbol = None
            if t < T - 1:
                next_symbol = sequence[t + 1][_TEXT]  # not found? FIXME
            xi = symbol_to_number[symbol]

            next_outputs_logprob = model._outputs_vector(next_symbol)
            alpha_plus_beta = alpha[t] + beta[t]

            if t < T - 1:
                numer_add = (
                    transitions_logprob
                    + next_outputs_logprob
                    + beta[t + 1]
                    + alpha[t].reshape(N, 1)
                )
                A_numer = np.logaddexp2(A_numer, numer_add)
                A_denom = np.logaddexp2(A_denom, alpha_plus_beta)
            else:
                B_denom = np.logaddexp2(A_denom, alpha_plus_beta)

            B_numer[:, xi] = np.logaddexp2(B_numer[:, xi], alpha_plus_beta)

        return lpk, A_numer, A_denom, B_numer, B_denom

    def train_unsupervised(self, unlabeled_sequences, update_outputs=True, **kwargs):
        """
        Trains the HMM using the Baum-Welch algorithm to maximise the
        probability of the data sequence. This is a variant of the EM
        algorithm, and is unsupervised in that it doesn't need the state
        sequences for the symbols. The code is based on 'A Tutorial on Hidden
        Markov Models and Selected Applications in Speech Recognition',
        Lawrence Rabiner, IEEE, 1989.

        :return: the trained model
        :rtype: HiddenMarkovModelTagger
        :param unlabeled_sequences: the training data, a set of
            sequences of observations
        :type unlabeled_sequences: list

        kwargs may include following parameters:

        :param model: a HiddenMarkovModelTagger instance used to begin
            the Baum-Welch algorithm
        :param max_iterations: the maximum number of EM iterations
        :param convergence_logprob: the maximum change in log probability to
            allow convergence
        """

        # create a uniform HMM, which will be iteratively refined, unless
        # given an existing model
        model = kwargs.get("model")
        if not model:
            priors = RandomProbDist(self._states)
            transitions = DictionaryConditionalProbDist(
                {state: RandomProbDist(self._states) for state in self._states}
            )
            outputs = DictionaryConditionalProbDist(
                {state: RandomProbDist(self._symbols) for state in self._states}
            )
            model = HiddenMarkovModelTagger(
                self._symbols, self._states, transitions, outputs, priors
            )

        self._states = model._states
        self._symbols = model._symbols

        N = len(self._states)
        M = len(self._symbols)
        symbol_numbers = {sym: i for i, sym in enumerate(self._symbols)}

        # update model prob dists so that they can be modified
        # model._priors = MutableProbDist(model._priors, self._states)

        model._transitions = DictionaryConditionalProbDist(
            {
                s: MutableProbDist(model._transitions[s], self._states)
                for s in self._states
            }
        )

        if update_outputs:
            model._outputs = DictionaryConditionalProbDist(
                {
                    s: MutableProbDist(model._outputs[s], self._symbols)
                    for s in self._states
                }
            )

        model.reset_cache()

        # iterate until convergence
        converged = False
        last_logprob = None
        iteration = 0
        max_iterations = kwargs.get("max_iterations", 1000)
        epsilon = kwargs.get("convergence_logprob", 1e-6)

        while not converged and iteration < max_iterations:
            A_numer = _ninf_array((N, N))
            B_numer = _ninf_array((N, M))
            A_denom = _ninf_array(N)
            B_denom = _ninf_array(N)

            logprob = 0
            for sequence in unlabeled_sequences:
                sequence = list(sequence)
                if not sequence:
                    continue

                (
                    lpk,
                    seq_A_numer,
                    seq_A_denom,
                    seq_B_numer,
                    seq_B_denom,
                ) = self._baum_welch_step(sequence, model, symbol_numbers)

                # add these sums to the global A and B values
                for i in range(N):
                    A_numer[i] = np.logaddexp2(A_numer[i], seq_A_numer[i] - lpk)
                    B_numer[i] = np.logaddexp2(B_numer[i], seq_B_numer[i] - lpk)

                A_denom = np.logaddexp2(A_denom, seq_A_denom - lpk)
                B_denom = np.logaddexp2(B_denom, seq_B_denom - lpk)

                logprob += lpk

            # use the calculated values to update the transition and output
            # probability values
            for i in range(N):
                logprob_Ai = A_numer[i] - A_denom[i]
                logprob_Bi = B_numer[i] - B_denom[i]

                # We should normalize all probabilities (see p.391 Huang et al)
                # Let sum(P) be K.
                # We can divide each Pi by K to make sum(P) == 1.
                #   Pi' = Pi/K
                #   log2(Pi') = log2(Pi) - log2(K)
                logprob_Ai -= logsumexp2(logprob_Ai)
                logprob_Bi -= logsumexp2(logprob_Bi)

                # update output and transition probabilities
                si = self._states[i]

                for j in range(N):
                    sj = self._states[j]
                    model._transitions[si].update(sj, logprob_Ai[j])

                if update_outputs:
                    for k in range(M):
                        ok = self._symbols[k]
                        model._outputs[si].update(ok, logprob_Bi[k])

                # Rabiner says the priors don't need to be updated. I don't
                # believe him. FIXME

            # test for convergence
            if iteration > 0 and abs(logprob - last_logprob) < epsilon:
                converged = True

            safe_print("iteration", iteration, "logprob", logprob)
            iteration += 1
            last_logprob = logprob

        return model

    def train_supervised(self, labelled_sequences, estimator=None):
        """
        Supervised training maximising the joint probability of the symbol and
        state sequences. This is done via collecting frequencies of
        transitions between states, symbol observations while within each
        state and which states start a sentence. These frequency distributions
        are then normalised into probability estimates, which can be
        smoothed if desired.

        :return: the trained model
        :rtype: HiddenMarkovModelTagger
        :param labelled_sequences: the training data, a set of
            labelled sequences of observations
        :type labelled_sequences: list
        :param estimator: a function taking
            a FreqDist and a number of bins and returning a CProbDistI;
            otherwise a MLE estimate is used
        """

        # default to the MLE estimate
        if estimator is None:
            estimator = lambda fdist, bins: MLEProbDist(fdist)

        # count occurrences of starting states, transitions out of each state
        # and output symbols observed in each state
        known_symbols = set(self._symbols)
        known_states = set(self._states)

        starting = FreqDist()
        transitions = ConditionalFreqDist()
        outputs = ConditionalFreqDist()
        for sequence in labelled_sequences:
            lasts = None
            for token in sequence:
                state = token[_TAG]
                symbol = token[_TEXT]
                if lasts is None:
                    starting[state] += 1
                else:
                    transitions[lasts][state] += 1
                outputs[state][symbol] += 1
                lasts = state

                # update the state and symbol lists
                if state not in known_states:
                    self._states.append(state)
                    known_states.add(state)

                if symbol not in known_symbols:
                    self._symbols.append(symbol)
                    known_symbols.add(symbol)

        # create probability distributions (with smoothing)
        N = len(self._states)
        pi = estimator(starting, N)
        A = ConditionalProbDist(transitions, estimator, N)
        B = ConditionalProbDist(outputs, estimator, len(self._symbols))

        return HiddenMarkovModelTagger(self._symbols, self._states, A, B, pi)


def _ninf_array(shape):
    res = np.empty(shape, np.float64)
    res.fill(-np.inf)
    return res


